#!/usr/bin/env node
// Concatenates src/*.css into dist/useful.css (and docs/useful.css for the guide).
// Usage: node scripts/build.mjs [--check]   (--check fails if the committed files are out of date)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const version = readFileSync(join(root, 'VERSION'), 'utf8').trim();
const parts = ['tokens.css', 'base.css', 'components.css'].map((f) => readFileSync(join(root, 'src', f), 'utf8').trimEnd());
const banner = `/*! useful-design v${version} - https://github.com/hsk-dk/useful-design - generated by scripts/build.mjs, do not edit */\n`;
const output = banner + parts.join('\n\n') + '\n';

const targets = ['dist/useful.css', 'docs/useful.css'];
const check = process.argv.includes('--check');
let stale = false;
for (const t of targets) {
	const path = join(root, t);
	if (check) {
		if (!existsSync(path) || readFileSync(path, 'utf8') !== output) {
			console.error(`${t} is out of date. Run: node scripts/build.mjs`);
			stale = true;
		}
	} else {
		mkdirSync(dirname(path), { recursive: true });
		writeFileSync(path, output);
		console.log(`wrote ${t} (${output.length} bytes, v${version})`);
	}
}
if (stale) process.exit(1);
if (check) console.log('dist is up to date');
